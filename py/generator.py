PREFIX = ["", "您好，", "亲，", "我们这边", "按规定", "实话跟您说，"]
SUFFIX = ["", "，谢谢理解", "，这是规定", "，您考虑下"]


def random_line():
    """返回 (文本, 真实类型 or None, 是否属于规则词表覆盖的写法)。"""
    if random.random() < 0.30:
        # 正常样本必须显式标记，不能再用 None 表示。
        # None 现在统一表示“未标注”，否则手输文本会被错误计入误报率。
        return random.choice(NORMAL), "正常沟通", True
    tpl, typ, slots, covered = random.choice(TEMPLATES)
    text = tpl.replace("{x}", random.choice(slots))
    text = random.choice(PREFIX) + text + random.choice(SUFFIX)
    return text, typ, covered


def batch(n):
    return [random_line() for _ in range(n)]
