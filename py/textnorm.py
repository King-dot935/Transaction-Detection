# -*- coding: utf-8 -*-
"""文本清洗与表达归一。

分三层，每层职责单一：

  clean()      字符层：全半角、零宽字符、emoji、脱敏、重复标点
  canonical()  词面层：同义词归一（退钱→退款、删评论→删差评）
  templatize() 句式层：把"能退吗/可以退吗/退货行吗"归到同一模板

不做语义理解——语义层交给 embedding 或小模型，这里只做"确定能做的归一"。
"""
import re
import unicodedata

# ---------------------------------------------------------------- 字符层
ZERO_WIDTH = dict.fromkeys(map(ord, "\u200b\u200c\u200d\u2060\ufeff"), None)

EMOJI_RE = re.compile(
    "[" "\U0001F300-\U0001FAFF" "\U00002600-\U000027BF" "\U0001F000-\U0001F2FF" "]+",
    flags=re.UNICODE)

# 脱敏：顺序很重要，先长后短
PATTERNS = [
    (re.compile(r"(?<!\d)1[3-9]\d{9}(?!\d)"), "<电话>"),             # 手机号
    (re.compile(r"(?<!\d)\d{17}[\dXx](?![\dXx])"), "<身份证>"),       # 身份证
    (re.compile(r"(?<!\d)\d{16,19}(?!\d)"), "<卡号>"),               # 银行卡
    (re.compile(r"(订单号?|单号)[:：]?\s*[A-Za-z0-9\-]{6,}"), "<订单号>"),
]


def clean(text):
    """字符层清洗：只做确定无损的处理。"""
    s = str(text or "")
    s = unicodedata.normalize("NFKC", s)          # 全角５ → 5
    s = s.translate(ZERO_WIDTH)                   # 零宽字符/BOM
    s = EMOJI_RE.sub("", s)                       # emoji
    for pat, repl in PATTERNS:                    # 脱敏
        s = pat.sub(repl, s)
    s = re.sub(r"[。、，；,;]{2,}", "，", s)          # 重复标点压缩
    s = re.sub(r"[!！?？]{2,}", "？", s)
    s = re.sub(r"\s+", " ", s).strip()
    return s


# ---------------------------------------------------------------- 词面层
# 同义词：只收"确定同义"的词，宁缺勿滥
SYNONYMS = {
    # 退款/退货
    "退钱": "退款", "退我钱": "退款", "返钱": "返现", "返红包": "返现",
    "退货退款": "退款", "退个款": "退款", "退一下": "退款",
    # 评价
    "删评论": "删差评", "撤评论": "删差评", "删评价": "删差评", "删评": "删差评",
    "改评论": "改差评", "改评价": "改差评", "撤差评": "删差评",
    "五星": "好评", "给个好评": "好评", "好评返现": "好评返现",
    # 私下交易
    "私聊": "加微信", "私下聊": "加微信", "加个微信": "加微信",
    "加v": "加微信", "加V": "加微信", "转私": "加微信",
    # 证件
    "证件": "身份证", "身份证照": "身份证", "身份证照片": "身份证",
    "身份证件": "身份证",
    # 发票
    "开票": "开票", "发票": "发票", "票据": "发票",
    # 拖延
    "过几天": "再等等", "等等再看": "再等等", "晚点再说": "再等等",
}

# 正则型同义：动词换了、对象没换的说法
REGEX_SYNONYMS = [
    (re.compile(r"(撤|删|清|弄)(掉|了)?[^，。]{0,4}(评论|评价|差评)"), "删差评"),
    (re.compile(r"(评论|评价|差评)[^，。]{0,4}(撤|删|清)(掉|了)?"), "删差评"),
    (re.compile(r"(给|补|返)(你|您)?[^，。]{0,3}(钱|红包|现)"), "返现"),
    (re.compile(r"(加|留|发)(个|一下)?(微信|v|V)"), "加微信"),
    (re.compile(r"(拍|发|传)(个|一下)?(证件|身份证|照片)"), "身份证"),
    (re.compile(r"(等|过)[一二三四五六七八九十\d]+(天|个工作日)"), "再等等"),
]

# 长词优先替换，避免"删评论"被"删评"截断
_SYN_KEYS = sorted(SYNONYMS, key=len, reverse=True)


def canonical(text):
    """词面层：正则型 + 词典型同义归一，并压掉叠词。"""
    s = clean(text)
    for pat, tag in REGEX_SYNONYMS:
        s = pat.sub(tag, s)
    for k in _SYN_KEYS:
        if k in s:
            s = s.replace(k, SYNONYMS[k])
    # 替换后可能出现「退款退款」，压成一个
    s = re.sub(r"(.{2,4}?)\1+", r"\1", s)
    return s


# ---------------------------------------------------------------- 句式层
# 把常见问法收敛成意图模板：能不能退 / 多久到 / 多少钱
TEMPLATES = [
    # 备选必须长的在前：退货|退款|退，否则「退」先命中会截断成「退货货吗」
    (re.compile(r"(能不能|可不可以|能|可以|支持)[^，。]{0,3}(退货|退款|退换|退)"
                r"(?=[吗么嘛不吧？。，!！]|$)"), "能否退货"),
    (re.compile(r"(能不能|可不可以|能|可以|支持)[^，。]{0,3}(换货|换)"
                r"(?=[吗么嘛不吧？。，!！]|$)"), "能否换货"),
    (re.compile(r"(多久|几天|什么时候)[^，。]{0,4}(到|发货|送达)"), "多久到货"),
    (re.compile(r"(多少|几)[^，。]{0,3}(钱|块|元)"), "多少钱"),
    (re.compile(r"(有没有|有)[^，。]{0,3}(发票)"), "有没有发票"),
    (re.compile(r"(为什么|凭什么|怎么)[^，。]{0,3}(不能|不给|不行)"), "为什么不行"),
]


def templatize(text):
    """句式层：命中模板则替换为意图短语，否则原样返回。"""
    s = canonical(text)
    for pat, tag in TEMPLATES:
        m = pat.search(s)
        if m:
            s = s[:m.start()] + tag + s[m.end():]
    return s


def squash(text):
    """用于相似度的紧凑形式：去标点与空白、小写。"""
    s = templatize(text)
    return re.sub(r"[\s\W_]+", "", s, flags=re.U).lower()
